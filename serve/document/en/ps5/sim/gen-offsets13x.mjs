// gen-offsets13x.mjs — parses X1NON-PSJB 13.XX offset files into a classic
// script module (window.X1NON_13X) that runtime.html loads before bridge.js.
// Source: https://github.com/X1NONs/X1NON-PSJB/tree/main/offsets/13.XX
import fs from "node:fs";
import path from "node:path";
import url from "node:url";

const HERE = path.dirname(url.fileURLToPath(import.meta.url));
const SRC = path.resolve(HERE, "../offsets/13.XX");
const OUT = path.resolve(HERE, "../modules/offsets13x.js");

function parseBlock(src, name) {
    const re = new RegExp("(?:let|const)\\s+" + name + "\\s*=\\s*\\{([\\s\\S]*?)\\n\\};");
    const m = re.exec(src);
    if (!m) throw new Error("block not found: " + name);
    const out = {};
    // quoted keys (several per line possible): "mov [rdi], rsi": 0x000C05B6,
    let k = /"([^"]+)"\s*:\s*(0x[0-9A-Fa-f]+)/g;
    let hit;
    while ((hit = k.exec(m[1])) !== null) out[hit[1]] = parseInt(hit[2], 16);
    // numeric keys: 0x014: 0x0001B860, 0x018: ... -> normalize to decimal string
    k = /0x([0-9A-Fa-f]+)\s*:\s*(0x[0-9A-Fa-f]+)/g;
    while ((hit = k.exec(m[1])) !== null)
        out[String(parseInt(hit[1], 16))] = parseInt(hit[2], 16);
    return out;
}

const files = fs.readdirSync(SRC).sort();
const data = {};
for (const f of files) {
    const src = fs.readFileSync(path.join(SRC, f), "utf8");
    const wk = parseBlock(src, "wk_gadgetmap");
    const sys = parseBlock(src, "syscall_map");
    data[f] = { wkGadgets: wk, syscallStubs: sys };
    console.log(`${f}: ${Object.keys(wk).length} wk gadgets, ${Object.keys(sys).length} syscall stubs`);
}

// sanity: getpid stub (0x14=20) must match the gpe we had interpolated
for (const [fw, d] of Object.entries(data)) {
    const getpid = d.syscallStubs["20"];
    console.log(`${fw}: getpid stub = 0x${getpid.toString(16)} (expect 0x1b860)`);
}

const banner = `// GENERATED by sim/gen-offsets13x.mjs from X1NON-PSJB offsets/13.XX — DO NOT EDIT.
// Source: https://github.com/X1NONs/X1NON-PSJB (libSceNKWebKit / libkernel_web / libSceLibcInternal).
// Classic script: defines window.X1NON_13X = { "<fw>": { wkGadgets, syscallStubs } }.
`;
let js = banner + "window.X1NON_13X = {\n";
for (const [fw, d] of Object.entries(data)) {
    js += `"${fw}": {\n  wkGadgets: {\n`;
    for (const [k, v] of Object.entries(d.wkGadgets))
        js += `    ${JSON.stringify(k)}: 0x${v.toString(16)},\n`;
    js += "  },\n  syscallStubs: {\n";
    const keys = Object.keys(d.syscallStubs).sort((a, b) => Number(a) - Number(b));
    for (const k of keys)
        js += `    "${k}": 0x${d.syscallStubs[k].toString(16)},\n`;
    js += "  },\n},\n";
}
js += "};\n";
fs.writeFileSync(OUT, js);
console.log("wrote", OUT, js.length, "bytes");